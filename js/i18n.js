  function readStored() {
    try { return localStorage.getItem(STORAGE_KEY); } catch { return null; }
  }
  function writeStored(code) {
    try { localStorage.setItem(STORAGE_KEY, code); } catch {}
  }
  function initialLang() {
    try {
      const q = (new URLSearchParams(location.search).get('lang') || '').toLowerCase();
      if (STR[q]) return q;
    } catch {}
    const s = readStored();
    if (s && STR[s]) return s;
    return DEFAULT;
  }

  let lang = initialLang();
  const listeners = [];
  const info = code => LANGS.find(l => l.code === code) || LANGS[0];

  function t(key, params) {
    let s = STR[lang] && STR[lang][key];
    if (s == null) s = it[key];
    if (s == null) return key;
    if (params) s = s.replace(/\{(\w+)\}/g, (m, k) => (params[k] != null ? String(params[k]) : m));
    return s;
  }
  const has = key => it[key] != null;

  const nfCache = {};
  function nf(opts) {
    const k = lang + JSON.stringify(opts || {});
    if (!nfCache[k]) {
      try { nfCache[k] = new Intl.NumberFormat(info(lang).locale, opts); }
      catch { nfCache[k] = new Intl.NumberFormat('it-IT', opts); }
    }
    return nfCache[k];
  }
  function fmtNum(n, opts) { return nf(opts).format(n); }
  function fmtPrice(n) {
    const v = Number(n);
    if (!isFinite(v)) return '';
    return nf({ style: 'currency', currency: 'EUR' }).format(v);
  }
  // distanza in metri -> "350 m" / "1,2 km"
  function fmtDist(m) {
    if (m == null || !isFinite(m)) return '';
    if (m < 1000) return Math.round(m) + ' m';
    return fmtNum(m / 1000, { minimumFractionDigits: 1, maximumFractionDigits: 1 }) + ' km';
  }
  function typeLabel(type) {
    const k = TYPE_KEYS[type];
    return k ? t(k) : (type || '');
  }
  function amenityLabel(a) {
    const k = AMENITY_KEYS[a];
    return k ? t(k) : t('type.venue');
  }

  // ---------------- Testo statico (data-i18n*) ----------------
  function applyStatic(root) {
    root = root || document;
    root.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.getAttribute('data-i18n')); });
    root.querySelectorAll('[data-i18n-html]').forEach(el => { el.innerHTML = t(el.getAttribute('data-i18n-html')); });
    root.querySelectorAll('[data-i18n-placeholder]').forEach(el => { el.setAttribute('placeholder', t(el.getAttribute('data-i18n-placeholder'))); });
    root.querySelectorAll('[data-i18n-title]').forEach(el => { el.setAttribute('title', t(el.getAttribute('data-i18n-title'))); });
    root.querySelectorAll('[data-i18n-aria-label]').forEach(el => { el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria-label'))); });
  }
  function applyDocument() {
    document.documentElement.lang = lang;
    document.title = t('meta.title');
    const md = document.querySelector('meta[name="description"]');
    if (md) md.setAttribute('content', t('meta.desc'));
    const sel = document.getElementById('langSelect');
    if (sel && sel.value !== lang) sel.value = lang;
    const code = document.getElementById('langCode');
    if (code) code.textContent = info(lang).short;
  }

  function setLang(code, opts) {
    code = String(code || '').toLowerCase();
    if (!STR[code]) return;
    if (!opts || opts.save !== false) writeStored(code);
    // se l'URL contiene ?lang=xx lo allinea, cosi' un ricaricamento non torna indietro
    try {
      const u = new URL(location.href);
      if (u.searchParams.has('lang') && u.searchParams.get('lang') !== code) {
        u.searchParams.set('lang', code);
        history.replaceState(history.state, '', u.toString());
      }
    } catch {}
    if (code === lang) return;
    lang = code;
    api.lang = code;
    applyDocument();
    applyStatic();
    listeners.forEach(cb => { try { cb(code); } catch (e) { console.error(e); } });
  }
  function onChange(cb) { if (typeof cb === 'function') listeners.push(cb); }

  function init() {
    const sel = document.getElementById('langSelect');
    if (sel) {
      sel.value = lang;
      sel.addEventListener('change', () => setLang(sel.value));
    }
    applyDocument();
    applyStatic();
  }

